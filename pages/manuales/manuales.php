    <h1 class="manual-title">Instalacion y mantenimiento</h1>

    <p class="manual-text">
      Para instalar y mantener el sistema de seguimiento de aprendices (SSA), se nesecita lo siguiente:
    </p>

    <p class="manual-list">
      -	Un servidor web con soporte para PHP y MySQL (por ejemplo, XAMPP, WAMP, LAMP).
      -	Acceso a la base de datos MySQL.
      -	Conocimientos básicos de administración de servidores web y bases de datos.
      -	Procedimiento de instalación:
          1. Descargar los archivos del sistema SSA desde el repositorio oficial.
          2. Configurar el servidor web y la base de datos MySQL.
          3. Importar el archivo SQL proporcionado para crear las tablas necesarias en la base de datos.
          4. Configurar el archivo de conexión a la base de datos con las credenciales correspondientes.
          5. Subir los archivos del sistema al servidor web.
          6. Acceder a la aplicación a través del navegador web.
      -	Mantenimiento:
          1. Realizar copias de seguridad periódicas de la base de datos y los archivos del sistema.
          2. Actualizar el sistema regularmente para corregir errores y mejorar la funcionalidad.
          3. Monitorear el rendimiento del servidor y optimizar la configuración según sea necesario.
          4. Proporcionar soporte técnico a los usuarios en caso de problemas o dudas.
    </p>

